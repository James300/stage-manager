function dialogueBlocks(
  sectionId: string,
  sectionTitle: string,
  entries: ReadonlyArray<readonly [string, string, string]>,
): ScriptBlock[] {
  return entries.map(([id, characterId, text]) => ({
    id,
    sectionId,
    sectionTitle,
    type: "dialogue",
    characterId,
    text,
  }));
}

